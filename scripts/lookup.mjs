#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const reference = new URL('../references/llms-full.txt', import.meta.url);
const index = new URL('../references/index.md', import.meta.url);
const usage = `Usage:
  node lookup.mjs --list [query]
  node lookup.mjs --index
  node lookup.mjs <section> [--start <line>] [--limit <count>]

Section names match exactly, ignoring case. Lines are relative to the section.
Output defaults to 160 lines; use pagination for examples and API tables.
The first section is named Overview. No dependencies or network access required.`;

function main(args) {
	if (!args.length || args.includes('--help')) {
		console.log(usage);
		return;
	}

	const text = readFileSync(reference, 'utf8');
	const lines = text.split(/\r?\n/);
	if (lines.at(-1) === '') lines.pop();
	const sections = [{ name: 'Overview', start: 1 }];
	let fence;
	for (const [i, line] of lines.entries()) {
		const marker = line.match(/^\s{0,3}(`{3,}|~{3,})(.*)$/);
		if (marker) {
			if (!fence) fence = marker[1];
			else if (marker[1][0] === fence[0] && marker[1].length >= fence.length && !marker[2].trim())
				fence = undefined;
			continue;
		}
		if (fence) continue;
		const heading = line.match(/^## (.+?)\s*$/);
		if (heading) sections.push({ name: heading[1], start: i + 1 });
	}
	for (const [i, section] of sections.entries()) {
		section.end = sections[i + 1] ? sections[i + 1].start - 1 : lines.length;
	}

	if (args[0] === '--index') {
		if (args.length !== 1) throw new Error('--index takes no arguments.');
		const hash = createHash('sha256').update(text).digest('hex');
		writeFileSync(
			index,
			[
				'# Carbon Svelte reference index',
				'',
				'Generated by `node ../scripts/lookup.mjs --index`. Do not edit manually.',
				'Line ranges refer to `llms-full.txt`; regenerate after replacing that file.',
				`SHA-256: \`${hash}\``,
				'',
				'| Section | Start line | End line |',
				'| --- | ---: | ---: |',
				...sections.map((s) => `| ${s.name} | ${s.start} | ${s.end} |`),
				''
			].join('\n')
		);
		console.log(`Indexed ${sections.length} sections in ${fileURLToPath(index)}`);
		return;
	}

	if (args[0] === '--list') {
		const query = args.slice(1).join(' ').toLowerCase();
		const matches = sections.filter((s) => s.name.toLowerCase().includes(query));
		if (!matches.length) throw new Error(`No sections matching "${query}".`);
		console.log(matches.map((s) => `${s.name}\t${s.start}-${s.end}`).join('\n'));
		return;
	}

	const name = args.shift();
	const section = sections.find((s) => s.name.toLowerCase() === name.toLowerCase());
	if (!section) throw new Error(`Unknown section "${name}". Use --list to discover names.`);
	let start = 1;
	let limit = 160;
	while (args.length) {
		const flag = args.shift();
		const value = args.shift();
		if (
			!['--start', '--limit'].includes(flag) ||
			!/^[1-9]\d*$/.test(value ?? '') ||
			!Number.isSafeInteger(Number(value))
		) {
			throw new Error('Expected --start or --limit followed by a positive integer.');
		}
		if (flag === '--start') start = Number(value);
		else limit = Number(value);
	}
	const length = section.end - section.start + 1;
	if (start > length) throw new Error(`Start line exceeds section length (${length}).`);
	const end = Math.min(length, start + limit - 1);
	console.log(
		`${section.name}: section lines ${start}-${end} of ${length}; source lines ${section.start + start - 1}-${section.start + end - 1}\n`
	);
	console.log(lines.slice(section.start + start - 2, section.start + end - 1).join('\n'));
	if (end < length)
		console.log(`\nNext: node lookup.mjs "${section.name}" --start ${end + 1} --limit ${limit}`);
}

try {
	main(process.argv.slice(2));
} catch (error) {
	console.error(error.message);
	process.exitCode = 1;
}
